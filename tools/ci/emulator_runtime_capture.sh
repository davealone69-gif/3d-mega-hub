#!/usr/bin/env bash
# Runs on the CI host with adb available, immediately after the emulator has booted.
#
# Everything it learns is written to runtime-evidence/summary.md, which the workflow posts as a pull
# request comment. That indirection exists because this repository's workflow logs and artifacts are
# served from hosts that are not always reachable, while comments are.
#
# No step is allowed to abort the capture: a missing screenshot is still evidence.
set -u

APP_ID=com.davemega.hub
TEST_CLASS=com.davemega.hub.avatarforge.GeneratedAvatarRuntimeTest
OUT=runtime-evidence
SUMMARY="$OUT/summary.md"

mkdir -p "$OUT"
: > "$SUMMARY"

log() { echo "$*" >> "$SUMMARY"; }
section() { log ""; log "### $*"; }

section "Device"
{
  echo '```text'
  adb devices
  echo "sdk=$(adb shell getprop ro.build.version.sdk | tr -d '\r') abi=$(adb shell getprop ro.product.cpu.abi | tr -d '\r')"
  echo "model=$(adb shell getprop ro.product.model | tr -d '\r')"
  echo "gles=$(adb shell dumpsys SurfaceFlinger 2>/dev/null | grep -m1 -i 'GLES' | tr -d '\r')"
  echo '```'
} >> "$SUMMARY" 2>&1

section "Install"
adb install -r -t app/build/outputs/apk/debug/app-debug.apk > "$OUT/install-app.log" 2>&1
APP_INSTALL=$?
adb install -r -t app/build/outputs/apk/androidTest/debug/app-debug-androidTest.apk > "$OUT/install-test.log" 2>&1
TEST_INSTALL=$?
log "- debug APK install exit: \`$APP_INSTALL\`"
log "- androidTest APK install exit: \`$TEST_INSTALL\`"
if [ "$APP_INSTALL" -ne 0 ]; then
  { echo '```text'; tail -20 "$OUT/install-app.log"; echo '```'; } >> "$SUMMARY"
fi

section "Level 3/4: install, launch, and look at the screen"
adb logcat -c > /dev/null 2>&1
adb shell am force-stop "$APP_ID" > /dev/null 2>&1
adb shell am start -W -n "$APP_ID/.MainActivity" > "$OUT/launch.log" 2>&1
LAUNCH=$?
log "- \`am start -W\` exit: \`$LAUNCH\`"
{ echo '```text'; head -12 "$OUT/launch.log"; echo '```'; } >> "$SUMMARY"

sleep 12

adb shell dumpsys activity activities 2>/dev/null \
  | grep -E "mResumedActivity|ResumedActivity|topResumedActivity" | head -3 > "$OUT/resumed.txt"
{ echo '```text'; cat "$OUT/resumed.txt"; echo '```'; } >> "$SUMMARY"

# Raw screencap: no PNG decoder needed on the host.
adb exec-out screencap > "$OUT/frame.raw" 2> "$OUT/screencap.err"
python3 tools/ci/analyze_raw_screencap.py "$OUT/frame.raw" > "$OUT/pixels.txt" 2>&1
{ echo '```text'; cat "$OUT/pixels.txt" 2>/dev/null || echo "no pixel analysis"; echo '```'; } >> "$SUMMARY"

section "Crashes and engine log"
adb logcat -d -b crash > "$OUT/logcat-crash.txt" 2>&1
CRASH_LINES=$(wc -l < "$OUT/logcat-crash.txt" | tr -d ' ')
log "- crash buffer lines: \`$CRASH_LINES\`"
if [ "$CRASH_LINES" -gt 0 ]; then
  { echo '```text'; head -40 "$OUT/logcat-crash.txt"; echo '```'; } >> "$SUMMARY"
fi

adb logcat -d 2>/dev/null \
  | grep -iE "filament|avatarforge|AndroidRuntime|FATAL|UnsatisfiedLink|mega-hub|av_" \
  | head -120 > "$OUT/logcat-app.txt"
{ echo '```text'; head -60 "$OUT/logcat-app.txt"; echo '```'; } >> "$SUMMARY"

section "App-written diagnostics"
adb shell run-as "$APP_ID" find . -name "*.json" 2>/dev/null | head -10 > "$OUT/app-files.txt"
adb shell run-as "$APP_ID" ls -R files 2>/dev/null | head -30 >> "$OUT/app-files.txt"
{ echo '```text'; cat "$OUT/app-files.txt"; echo '```'; } >> "$SUMMARY"
for f in $(adb shell run-as "$APP_ID" find files -name "*.json" 2>/dev/null | head -3 | tr -d '\r'); do
  log ""
  log "<details><summary>\`$f\`</summary>"
  log ""
  log '```json'
  adb shell run-as "$APP_ID" cat "$f" 2>/dev/null | head -c 2000 >> "$SUMMARY"
  log '```'
  log "</details>"
done

section "Instrumentation: $TEST_CLASS"
adb shell am instrument -w -r -e class "$TEST_CLASS" \
  "$APP_ID.test/androidx.test.runner.AndroidJUnitRunner" > "$OUT/instrumentation.log" 2>&1
INSTRUMENT=$?
log "- \`am instrument\` exit: \`$INSTRUMENT\`"
{ echo '```text'; head -60 "$OUT/instrumentation.log"; echo '```'; } >> "$SUMMARY"

log ""
log "_Generated by tools/ci/emulator_runtime_capture.sh on run ${GITHUB_RUN_ID:-local}._"
exit 0
