#!/usr/bin/env python3
"""Turns the face-animation GLSL of the avatar shaders into C++ so a host test can run it.

    python3 face_glsl_to_cpp.py af_shaders_gl.h OUT.h

af_shaders_gl.h holds forward.vert and shadow.vert as C strings. Both carry afSmooth01() and
afFaceDelta(), written by hand as a transcription of FaceRig::evaluatePacked() (af_face.cpp).
No GLES implementation runs on a build machine, so nothing would notice a slip in that
transcription until a face looked wrong on a phone. This script

  * takes the text of the two functions out of both shaders and fails if they differ
    (a face that moves one way and its shadow another),
  * rewrites the two things C++ does not read as GLSL does: ".xyz" becomes ".xyz()" and every
    float literal gets an "f", so the arithmetic stays in single precision as on a GPU,
  * writes them, with a few lines of vector types, into namespace glsl_face.

The CMake host build runs it and animation_system_test compares glsl_face::afFaceDelta() with
af_face_evaluate_packed() on every vertex of a generated face. Standard library only.
"""
import re
import sys

SHADERS = ('kSrc_forward_vert', 'kSrc_shadow_vert')
START = 'float afSmooth01(float x) {'
END = 'void main() {'

PRELUDE = r'''/* GENERATED by tools/shader_check/face_glsl_to_cpp.py from af_shaders_gl.h. Do not edit. */
#ifndef AF_GLSL_FACE_GENERATED_H
#define AF_GLSL_FACE_GENERATED_H
#include <cmath>
namespace glsl_face {
struct vec3 {
    float x, y, z;
    vec3() : x(0), y(0), z(0) {}
    explicit vec3(float v) : x(v), y(v), z(v) {}
    vec3(float a, float b, float c) : x(a), y(b), z(c) {}
    vec3& operator+=(const vec3& o) { x += o.x; y += o.y; z += o.z; return *this; }
};
inline vec3 operator-(const vec3& a, const vec3& b) { return vec3(a.x - b.x, a.y - b.y, a.z - b.z); }
inline vec3 operator*(const vec3& a, const vec3& b) { return vec3(a.x * b.x, a.y * b.y, a.z * b.z); }
inline vec3 operator*(const vec3& a, float s) { return vec3(a.x * s, a.y * s, a.z * s); }
struct vec4 {
    float x, y, z, w;
    vec4() : x(0), y(0), z(0), w(0) {}
    vec3 xyz() const { return vec3(x, y, z); }
};
struct bvec3 { bool x, y, z; };
inline bvec3 lessThanEqual(const vec3& a, const vec3& b) { return bvec3{a.x <= b.x, a.y <= b.y, a.z <= b.z}; }
inline bvec3 greaterThanEqual(const vec3& a, const vec3& b) { return bvec3{a.x >= b.x, a.y >= b.y, a.z >= b.z}; }
inline bool any(const bvec3& v) { return v.x || v.y || v.z; }
inline float clamp(float v, float lo, float hi) { return v < lo ? lo : (v > hi ? hi : v); }
inline float dot(const vec3& a, const vec3& b) { return a.x * b.x + a.y * b.y + a.z * b.z; }
inline float sqrt(float v) { return std::sqrt(v); }
inline float abs(float v) { return std::fabs(v); }
inline int min(int a, int b) { return a < b ? a : b; }
/* The uniform block, with the layout of the shader's AfFaceBlock. */
struct AfFaceBlock {
    vec4 uFaceBoxMin;
    vec4 uFaceBoxMax;
    vec4 uFaceParams;
    vec4 uFaceKernels[%(kernels)d];
};
static AfFaceBlock afFace;
static const int kKernelVectors = %(kernels)d;

'''


def shader_text(header, name):
    found = re.search(r'static const char %s\[\] =\n(.*?)\n;\n' % name, header, re.S)
    if not found:
        raise SystemExit('face_glsl_to_cpp: %s is not in the header' % name)
    lines = []
    for line in found.group(1).split('\n'):
        line = line.strip()
        if not (line.startswith('"') and line.endswith('"')):
            raise SystemExit('face_glsl_to_cpp: unexpected line in %s: %s' % (name, line))
        lines.append(line[1:-1].encode('utf-8').decode('unicode_escape'))
    return ''.join(lines)


def face_functions(text, name):
    start = text.find(START)
    end = text.find(END)
    if start < 0 or end < start:
        raise SystemExit('face_glsl_to_cpp: %s has no afSmooth01()/afFaceDelta() before main()' % name)
    return text[start:end].strip() + '\n'


def kernel_vectors(text, name):
    found = re.search(r'vec4 uFaceKernels\[(\d+)\];', text)
    if not found:
        raise SystemExit('face_glsl_to_cpp: %s declares no uFaceKernels array' % name)
    return int(found.group(1))


def main(argv):
    if len(argv) != 3:
        raise SystemExit(__doc__)
    header = open(argv[1], encoding='utf-8').read()
    texts = [shader_text(header, name) for name in SHADERS]
    functions = [face_functions(text, name) for text, name in zip(texts, SHADERS)]
    if functions[0] != functions[1]:
        raise SystemExit('face_glsl_to_cpp: forward.vert and shadow.vert differ in afSmooth01()/afFaceDelta(); '
                         'the figure and its shadow would move differently')
    sizes = [kernel_vectors(text, name) for text, name in zip(texts, SHADERS)]
    if sizes[0] != sizes[1]:
        raise SystemExit('face_glsl_to_cpp: the two shaders size uFaceKernels differently: %s' % sizes)
    for text, name in zip(texts, SHADERS):
        if 'afFaceDelta(aPos)' not in text[text.find(END):]:
            raise SystemExit('face_glsl_to_cpp: main() of %s does not call afFaceDelta(aPos)' % name)
    body = functions[0]
    body = re.sub(r'\.xyz\b', '.xyz()', body)
    body = re.sub(r'(?<![\w.])(\d+\.\d+)(?![\w.])', r'\1f', body)
    with open(argv[2], 'w', encoding='utf-8') as out:
        out.write(PRELUDE % {'kernels': sizes[0]})
        out.write(body)
        out.write('} /* namespace glsl_face */\n#endif\n')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
